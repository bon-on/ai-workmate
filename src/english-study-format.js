export function buildFormattedLesson(rawContent) {
  const lesson = parseLesson(rawContent);
  if (!lesson) {
    return rawContent;
  }

  const vocabularyItems = lesson.vocabulary
    .map((word) => `- ${word}: ${lookupMeaning(word)}`)
    .join("\n");
  const keyPointItems = extractKeyPointWords(lesson)
    .map((word) => `- ${word}: ${lookupMeaning(word)}`)
    .join("\n");

  return [
    `Focus: ${lesson.focus}`,
    "",
    "Vocabulary list:",
    vocabularyItems,
    "",
    "Key point words:",
    keyPointItems,
    "",
    "Core pattern:",
    `- ${lesson.corePattern}`,
    "",
    `Mini reading: ${lesson.miniReading}`,
    "",
    "Example sentences:",
    ...lesson.exampleSentences.map((sentence) => `- ${sentence}`),
    "",
    `Speaking task: ${lesson.speakingTask}`,
    `Writing challenge: ${lesson.writingChallenge}`,
  ].join("\n");
}

export function parseLesson(rawContent) {
  const lines = rawContent.split("\n");
  const lesson = {
    focus: "",
    vocabulary: [],
    corePattern: "",
    miniReading: "",
    exampleSentences: [],
    speakingTask: "",
    writingChallenge: "",
  };

  let currentSection = null;

  for (const line of lines) {
    if (line.startsWith(LESSON_LABELS.focus)) {
      lesson.focus = line.slice(LESSON_LABELS.focus.length).trim();
      currentSection = null;
    } else if (line.startsWith("Vocabulary (") && line.includes("):")) {
      lesson.vocabulary = line
        .slice(line.indexOf(":") + 1)
        .split(",")
        .map((item) => item.trim())
        .filter(Boolean);
      currentSection = null;
    } else if (line.startsWith(LESSON_LABELS.exampleSentences)) {
      currentSection = "exampleSentences";
    } else if (currentSection === "exampleSentences" && line.startsWith("- ")) {
      lesson.exampleSentences.push(line.slice(2).trim());
    } else if (currentSection === "exampleSentences" && !line.trim()) {
      currentSection = null;
    } else if (line.startsWith(LESSON_LABELS.corePattern)) {
      lesson.corePattern = line.slice(LESSON_LABELS.corePattern.length).trim();
      currentSection = null;
    } else if (line.startsWith(LESSON_LABELS.miniReading)) {
      lesson.miniReading = line.slice(LESSON_LABELS.miniReading.length).trim();
      currentSection = null;
    } else if (line.startsWith(LESSON_LABELS.speakingTask)) {
      lesson.speakingTask = line.slice(LESSON_LABELS.speakingTask.length).trim();
      currentSection = null;
    } else if (line.startsWith(LESSON_LABELS.writingChallenge)) {
      lesson.writingChallenge = line.slice(LESSON_LABELS.writingChallenge.length).trim();
      currentSection = null;
    }
  }

  if (!lesson.focus || lesson.vocabulary.length === 0) {
    return null;
  }

  return lesson;
}

export function extractKeyPointWords(lesson) {
  const selected = [];
  const vocabularyMap = new Map(lesson.vocabulary.map((word) => [normalizeWord(word), word]));

  collectKeyPoints(selected, tokenizeEnglish(lesson.miniReading), vocabularyMap, true);
  collectKeyPoints(selected, tokenizeEnglish(lesson.corePattern), vocabularyMap, false);

  return selected.length > 0 ? selected : lesson.vocabulary.slice(0, Math.min(KEYPOINT_LIMIT, lesson.vocabulary.length));
}

export function lookupMeaning(word) {
  return VOCABULARY_GLOSSARY[normalizeWord(word)] || "의미 확인 필요";
}

function hasMeaning(word) {
  return Object.hasOwn(VOCABULARY_GLOSSARY, normalizeWord(word));
}

function collectKeyPoints(selected, tokens, vocabularyMap, vocabularyOnly) {
  if (selected.length >= KEYPOINT_LIMIT) {
    return;
  }

  for (const token of tokens) {
    const normalized = normalizeWord(token);
    if (KEYPOINT_STOP_WORDS.has(normalized)) {
      continue;
    }

    const canonicalVocabulary = resolveVocabularyWord(normalized, vocabularyMap);
    const candidate = canonicalVocabulary || (!vocabularyOnly && hasMeaning(token) ? normalized : null);
    if (!candidate || selected.includes(candidate)) {
      continue;
    }

    selected.push(candidate);
    if (selected.length >= KEYPOINT_LIMIT) {
      return;
    }
  }
}

function resolveVocabularyWord(normalizedToken, vocabularyMap) {
  if (vocabularyMap.has(normalizedToken)) {
    return vocabularyMap.get(normalizedToken);
  }

  if (normalizedToken.endsWith("s")) {
    const singular = normalizedToken.slice(0, -1);
    if (vocabularyMap.has(singular)) {
      return vocabularyMap.get(singular);
    }
  }

  return null;
}

function tokenizeEnglish(text) {
  return [...text.matchAll(/[A-Za-z][A-Za-z-]*/g)].map((match) => match[0]);
}

function normalizeWord(word) {
  return word.trim().toLowerCase();
}
